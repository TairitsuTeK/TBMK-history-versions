#include "port.h"
#include "mouse.h"
#include "wm.h"

static void set_vga_palette_full(void)
{
    outb(0x3C8, 0);
    for (int i = 0; i < 256; i++) {
        int r, g, b;
        
        if (i < 16) {
            // 标准VGA 16色
            static const unsigned char vga16[16][3] = {
                {0x00,0x00,0x00}, {0x00,0x00,0x2A}, {0x00,0x2A,0x00}, {0x00,0x2A,0x2A},
                {0x2A,0x00,0x00}, {0x2A,0x00,0x2A}, {0x2A,0x15,0x00}, {0x2A,0x2A,0x2A},
                {0x15,0x15,0x15}, {0x15,0x15,0x3F}, {0x15,0x3F,0x15}, {0x15,0x3F,0x3F},
                {0x3F,0x15,0x15}, {0x3F,0x15,0x3F}, {0x3F,0x3F,0x15}, {0x3F,0x3F,0x3F}
            };
            r = vga16[i][0];
            g = vga16[i][1];
            b = vga16[i][2];
        } else if (i < 32) {
            // 16级灰度
            int level = (i - 16) * 4;
            r = g = b = level;
        } else {
            // 其余颜色：均匀分布
            int n = i - 32;
            r = (n % 6) * 12;
            g = ((n / 6) % 6) * 12;
            b = ((n / 36) % 6) * 12;
        }
        
        outb(0x3C9, r);
        outb(0x3C9, g);
        outb(0x3C9, b);
    }
}
// 设置VGA 320x200x256模式
static void set_vga_mode_320x200x256(void)
{
    // MISC寄存器
    outb(0x3C2, 0x63);
    
    // Sequencer寄存器
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);
    outb(0x3C4, 0x01); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F);
    outb(0x3C4, 0x03); outb(0x3C5, 0x00);
    outb(0x3C4, 0x04); outb(0x3C5, 0x0E);
    
    // CRTC寄存器
    outb(0x3D4, 0x00); outb(0x3D5, 0x5F);
    outb(0x3D4, 0x01); outb(0x3D5, 0x4F);
    outb(0x3D4, 0x02); outb(0x3D5, 0x50);
    outb(0x3D4, 0x03); outb(0x3D5, 0x82);
    outb(0x3D4, 0x04); outb(0x3D5, 0x54);
    outb(0x3D4, 0x05); outb(0x3D5, 0x80);
    outb(0x3D4, 0x06); outb(0x3D5, 0xBF);
    outb(0x3D4, 0x07); outb(0x3D5, 0x1F);
    outb(0x3D4, 0x08); outb(0x3D5, 0x00);
    outb(0x3D4, 0x09); outb(0x3D5, 0x41);
    outb(0x3D4, 0x0A); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0B); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0C); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0D); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0E); outb(0x3D5, 0x00);
    outb(0x3D4, 0x0F); outb(0x3D5, 0x00);
    outb(0x3D4, 0x10); outb(0x3D5, 0x9C);
    outb(0x3D4, 0x11); outb(0x3D5, 0x8E);
    outb(0x3D4, 0x12); outb(0x3D5, 0x8F);
    outb(0x3D4, 0x13); outb(0x3D5, 0x28);
    outb(0x3D4, 0x14); outb(0x3D5, 0x40);
    outb(0x3D4, 0x15); outb(0x3D5, 0x96);
    outb(0x3D4, 0x16); outb(0x3D5, 0xB9);
    outb(0x3D4, 0x17); outb(0x3D5, 0xA3);
    
    // Graphics Controller寄存器
    outb(0x3CE, 0x00); outb(0x3CF, 0x00);
    outb(0x3CE, 0x01); outb(0x3CF, 0x00);
    outb(0x3CE, 0x02); outb(0x3CF, 0x00);
    outb(0x3CE, 0x03); outb(0x3CF, 0x00);
    outb(0x3CE, 0x04); outb(0x3CF, 0x00);
    outb(0x3CE, 0x05); outb(0x3CF, 0x40);
    outb(0x3CE, 0x06); outb(0x3CF, 0x05);
    outb(0x3CE, 0x07); outb(0x3CF, 0x0F);
    outb(0x3CE, 0x08); outb(0x3CF, 0xFF);
    
    // Attribute Controller寄存器
    inb(0x3DA);
    outb(0x3C0, 0x00); outb(0x3C0, 0x00);
    outb(0x3C0, 0x01); outb(0x3C0, 0x01);
    outb(0x3C0, 0x02); outb(0x3C0, 0x02);
    outb(0x3C0, 0x03); outb(0x3C0, 0x03);
    outb(0x3C0, 0x04); outb(0x3C0, 0x04);
    outb(0x3C0, 0x05); outb(0x3C0, 0x05);
    outb(0x3C0, 0x06); outb(0x3C0, 0x06);
    outb(0x3C0, 0x07); outb(0x3C0, 0x07);
    outb(0x3C0, 0x08); outb(0x3C0, 0x08);
    outb(0x3C0, 0x09); outb(0x3C0, 0x09);
    outb(0x3C0, 0x0A); outb(0x3C0, 0x0A);
    outb(0x3C0, 0x0B); outb(0x3C0, 0x0B);
    outb(0x3C0, 0x0C); outb(0x3C0, 0x0C);
    outb(0x3C0, 0x0D); outb(0x3C0, 0x0D);
    outb(0x3C0, 0x0E); outb(0x3C0, 0x0E);
    outb(0x3C0, 0x0F); outb(0x3C0, 0x0F);
    outb(0x3C0, 0x10); outb(0x3C0, 0x41);
    outb(0x3C0, 0x11); outb(0x3C0, 0x00);
    outb(0x3C0, 0x12); outb(0x3C0, 0x0F);
    outb(0x3C0, 0x13); outb(0x3C0, 0x00);
    outb(0x3C0, 0x14); outb(0x3C0, 0x00);
    inb(0x3DA);
    outb(0x3C0, 0x20);
    
    // 设置调色板
    set_vga_palette_full();
}

void kernel_main(void)
{
    set_vga_mode_320x200x256();
    
    unsigned char* v = (unsigned char*)0xA0000;
    int mx, my, mb, last_mx = -1, last_my = -1, last_mb = 0;

    // 清屏为灰色
    for (int i = 0; i < 320 * 200; i++) {
        v[i] = 7;
    }

    wm_init();
    wm_draw(v);
    mouse_init();

    while (1) {
        if (inb(0x64) & 0x01) {
            unsigned char st = inb(0x64);
            if (st & 0x20) mouse_handle_byte(inb(0x60));
            else inb(0x60);
        }
        mouse_get(&mx, &my, &mb);
        int mb_press = (mb & 1) && !(last_mb & 1);
        int mb_release = !(mb & 1) && (last_mb & 1);
        last_mb = mb;

        wm_update(v, mx, my, mb, mb_press, mb_release);
        wm_draw(v);

        if (wm_need_mouse_reset()) {
            mouse_reset();
            last_mx = -1; last_my = -1;
        }

        if (!wm_is_dragging() && (mx != last_mx || my != last_my)) {
            mouse_draw(v);
            last_mx = mx; last_my = my;
        }
    }
}